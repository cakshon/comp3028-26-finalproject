BEGIN;

CREATE TABLE IF NOT EXISTS Organisation (
    organisationID int PRIMARY KEY,
    organisationName varchar(50),
    contactEmail varchar(50),
    approvalStatus bit
);

CREATE TABLE IF NOT EXISTS FoodListing (
    listingID int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organisationID int REFERENCES Organisation(organisationID),
    listingName varchar(50) NOT NULL,
    reservationStatus bit NOT NULL
);

COMMIT;